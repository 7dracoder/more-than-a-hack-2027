"""Package the v0.3 source snapshot and generate a separate CPU Colab notebook."""

import argparse
import json

from build_colab import ROOT, bundle, digest, notebook


def build(bundle_id, reuse=False, revision=False):
    tag = 'v031' if revision else 'v03'
    target = ROOT / f'data/drive-transfer/BlindSpot_{tag}_project.zip'
    target.parent.mkdir(parents=True, exist_ok=True)
    checksum = digest(target) if reuse else bundle(target)
    output = ROOT / f'notebooks/BlindSpot_{tag}_Colab.ipynb'
    notebook(bundle_id, checksum, output)
    obj = json.loads(output.read_text())
    obj['metadata']['colab']['name'] = output.name
    for cell in obj['cells']:
        text = ''.join(cell['source'])
        if cell['cell_type'] == 'markdown':
            if text.startswith('# BlindSpot:'):
                text = '# BlindSpot v0.3: train, audit, reproduce\n\nCPU-only candidate suite with trajectory-derived movement, explicit speed-unit consistency checks, factorized possession inference, symmetric gradient boosting, whole-run purged cross-fitting and uncertainty-driven review. No GPU purchase or hosted LLM is required. Public data is a previously inspected development example; these experiments do not establish a private-match ranking.\n'
            elif text.startswith('## Mathematical'):
                text = '## Correctness checks\n\nTests cover exact inference, unit semantics, trajectory continuity, restart ownership, team-swap invariance, training-label isolation, complete-run fold purging, halftime reset and corrupted/interrupted checkpoint recovery.\n'
            elif text.startswith('## Run the experiment'):
                text = '## Train and evaluate the fixed candidates\n\nThree fixed approaches, no large hyperparameter search. Four contiguous evaluation folds preserve entire H/A/D runs; training excludes those folds and neighbouring runs with a 300-frame embargo. Report pooled matching counts over the same folds for all methods. The final exported classifier is fitted on ALL public labels; its training-window score is descriptive, not validation. Older metadata-scaling pilot results are not the trajectory-based result.\n'
            elif text.startswith('## Explore evidence'):
                text = '## Inspect the result\n\nColab shows a static dashboard preview. Download and extract the archive for working local links and the interactive evidence report. The default cloud run does not download videos or build clips. Local video demo: install requirements-v3-video.txt and run scripts/build_candidate_review.py with permitted tactical assets.\n'
            elif text.startswith('## Save results'):
                text = '## Save results before disconnecting\n\nThe archive includes the provisional candidate CSV, source/input/output hashes, fitted models, four-fold development evidence, unit audit, missing-ball stress test and review risk. Model files were generated by this notebook; only load trusted model artifacts. Keep match-derived results within the permitted sharing scope.\n'
        else:
            text = text.replace("'/content/blindspot'", "'/content/blindspot-v03'").replace("'/content/BlindSpot_project.zip'", "'/content/BlindSpot_v03_project.zip'")
            if text.startswith('%pip'):
                text = '%pip -q install numpy==2.2.6 pandas==2.2.3 scipy==1.17.1 scikit-learn==1.8.0 joblib==1.5.3 threadpoolctl==3.6.0 gdown==5.2.0\n'
            elif 'import gdown' in text:
                text += "os.environ['LOKY_MAX_CPU_COUNT'] = '2'\n"
            elif "'unittest'" in text:
                text = "result = subprocess.run([sys.executable, '-m', 'unittest', 'discover', '-s', 'tests', '-v'], capture_output=True, text=True)\nprint(result.stdout)\nprint(result.stderr)\nresult.check_returncode()\n"
            elif "'scripts/run_experiment.py'" in text:
                text = "result = subprocess.run([sys.executable, 'scripts/run_champion.py', '--out', str(OUT), '--resume', '--archive'], capture_output=True, text=True)\nprint(result.stdout)\nprint(result.stderr)\nresult.check_returncode()\n"
            elif text.startswith('OUT = PROJECT'):
                text = """subprocess.run([sys.executable, 'evaluation/validate_submission.py', str(OUT / 'candidate/CoreOrigin.csv')], check=True)
results = json.loads((OUT / 'supervised/pooled_scores.json').read_text())
import pandas as pd
display(pd.DataFrame(results).T[['macro_f1','spell_f1_mean','dead_f1','n_graded','scope']])
print('SPEED UNIT AUDIT')
print((OUT / 'evaluation/speed_unit_audit.json').read_text())
print('OUTPUT_CSV_HASHES')
print(json.dumps(json.loads((OUT / 'manifest.json').read_text())['output_csv_sha256'], indent=2))
"""
            elif 'display(HTML' in text:
                text = """from IPython.display import HTML, display
import re
preview = (OUT / 'index.html').read_text()
preview = re.sub(r'href="[^"]*"', '', preview)
display(HTML('<p>Static Colab preview. Download the result archive for working local links.</p>' + preview))
"""
            elif 'result_zip = shutil.make_archive' in text:
                text = text.replace("'/content/BlindSpot_results'", "'/content/BlindSpot_v03_results'")
        cell['source'] = text.splitlines(keepends=True)
    persistent = [
        {'cell_type': 'markdown', 'metadata': {}, 'source': ['## Optional durable output\n', 'Default output is temporary runtime storage. Set PERSIST_TO_DRIVE=True and authorize your own Drive mount to retain verified stages across runtime resets. This does not change sharing. Otherwise download the final ZIP.\n']},
        {'cell_type': 'code', 'metadata': {}, 'execution_count': None, 'outputs': [], 'source': [
            'PERSIST_TO_DRIVE = False\n', 'if PERSIST_TO_DRIVE:\n', '    from google.colab import drive\n', "    drive.mount('/content/drive')\n",
            "    OUT = Path('/content/drive/MyDrive/BlindSpot/checkpoints/v03')\n", 'else:\n',
            "    OUT = PROJECT / 'data/experiments/blindspot-v3'\n", 'OUT.mkdir(parents=True, exist_ok=True)\n',
            "print('Output:', OUT, '| durable:', PERSIST_TO_DRIVE)\n"]}]
    obj['cells'][4:4] = persistent
    if revision:
        for cell in obj['cells']:
            text = ''.join(cell['source']).replace('v0.3', 'v0.3.1').replace('v03', 'v031').replace('blindspot-v3', 'blindspot-v031')
            if cell['cell_type'] == 'code' and "'scripts/run_champion.py'" in text:
                text = """command = [sys.executable, '-u', 'scripts/run_champion.py', '--config', 'configs/champion_v031.json', '--out', str(OUT), '--resume', '--archive']
with subprocess.Popen(command, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, bufsize=1) as process:
    for line in process.stdout:
        print(line, end='', flush=True)
    status = process.wait()
if status:
    raise subprocess.CalledProcessError(status, command)
"""
            if cell['cell_type'] == 'markdown' and text.startswith('# BlindSpot'):
                text += '\nAudit revision: observation masks distinguish missing measurements from zero; team inference resets at algorithmically inferred stoppages. Owner support is conditional on the decoded live/dead segmentation. Additional fixed-time comparisons are a same-sample sensitivity audit, not independent validation.\n'
            cell['source'] = text.splitlines(keepends=True)
    output.write_text(json.dumps(obj, indent=2) + '\n', encoding='utf-8')
    print(json.dumps({'bundle': str(target), 'sha256': checksum, 'notebook': str(output)}, indent=2))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--bundle-id', default='SET_AFTER_DRIVE_UPLOAD')
    parser.add_argument('--reuse-bundle', action='store_true')
    parser.add_argument('--revision', action='store_true')
    args = parser.parse_args()
    build(args.bundle_id, args.reuse_bundle, args.revision)
